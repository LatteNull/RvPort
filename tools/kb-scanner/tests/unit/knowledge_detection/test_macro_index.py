"""Count domain reads rather than relying on host timing or source text."""
from dataclasses import replace
from pathlib import Path
import unittest
from unittest.mock import patch

from kb_scanner.core import FrontendSnapshot, CompletionStatus, stable_id
from kb_scanner.normalization.cpp import CppEvidenceNormalizer
from .support import make_context, make_entity, make_evidence


def macro_snapshot(size):
    entity = make_entity()
    definition = make_evidence(entity, "macro_definition", "WRAP")
    attachments = tuple(make_evidence(
        entity, "macro_parameter" if i % 2 else "macro_replacement_token", "x",
        line=i + 2, metadata={"macroDefinitionEvidenceId": definition.id, "ordinal": i, "tokenRole": "identifier"},
    ) for i in range(size))
    return FrontendSnapshot((entity,), (definition, *attachments))


class CountedEvidence:
    def __init__(self, value, reads):
        self.value_object, self.reads = value, reads

    def __getattr__(self, name):
        if name == "kind":
            self.reads.append(name)
        return getattr(self.value_object, name)


class MacroIndexTests(unittest.TestCase):
    def test_normalized_snapshot_matches_pre_optimization_commit(self):
        result = CppEvidenceNormalizer().normalize(make_context(Path("/tmp")), macro_snapshot(3))
        # Captured independently from 6c4b02c, not regenerated by the test.
        self.assertEqual("4a02532f004ff6d4d2171bc77ee313424d3a1609acc0232737ab9f00415aae0a",
                         stable_id("macro-baseline", result))

    def test_definition_lookup_has_linear_domain_reads(self):
        context = make_context(Path("/tmp"))
        for size in (32, 128, 512):
            snapshot = macro_snapshot(size)
            reads = []
            counted = replace(snapshot, evidence=tuple(CountedEvidence(x, reads) for x in snapshot.evidence))
            result = CppEvidenceNormalizer().normalize(context, counted)
            expected = CppEvidenceNormalizer().normalize(context, snapshot)
            self.assertEqual(expected.value.facts, result.value.facts)
            self.assertEqual(expected.diagnostics, result.diagnostics)
            self.assertLess(len(reads), 20 * len(snapshot.evidence), (size, len(reads)))

    def test_invalid_refs_and_cross_call_isolation(self):
        context = make_context(Path("/tmp"))
        normalizer = CppEvidenceNormalizer()
        snapshot = macro_snapshot(2)
        self.assertEqual(CompletionStatus.COMPLETE, normalizer.normalize(context, snapshot).status)
        for reference in (None, 9, stable_id("missing")):
            attachment = replace(snapshot.evidence[1], metadata={"macroDefinitionEvidenceId": reference})
            result = normalizer.normalize(context, replace(snapshot, evidence=(attachment,)))
            self.assertEqual(CompletionStatus.FAILED, result.status)
            self.assertIsNone(result.value)
            self.assertEqual(["normalization.invalid-macro-definition-reference"], [x.code for x in result.diagnostics])
        self.assertEqual(CompletionStatus.COMPLETE, normalizer.normalize(context, FrontendSnapshot()).status)

    def test_order_producers_contexts_and_derived_definition(self):
        normalizer = CppEvidenceNormalizer()
        context = make_context(Path("/tmp"))
        snapshot = macro_snapshot(3)
        definition, *attachments = snapshot.evidence
        duplicate = replace(attachments[0], id=stable_id("second"), producer="clang")
        configured = replace(attachments[1], id=stable_id("configured"), metadata={
            **attachments[1].metadata, "compilationContextId": stable_id("context")})
        values = (*snapshot.evidence, duplicate, configured)
        expected = normalizer.normalize(context, replace(snapshot, evidence=values))
        self.assertEqual(expected, normalizer.normalize(context, replace(snapshot, evidence=tuple(reversed(values)))))
        self.assertTrue(any(len(x.producers) == 2 for x in expected.value.facts))
        self.assertTrue(any(x.context_ids for x in expected.value.facts))
        with patch.object(CppEvidenceNormalizer, "_compiler_argument_evidence", return_value=((definition,), ())):
            self.assertEqual(expected, normalizer.normalize(context, replace(snapshot, evidence=values[1:])))
